-- 1. Tabela de Cargos e Permissões
CREATE TABLE IF NOT EXISTS cargos_permissoes (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nome TEXT NOT NULL UNIQUE,
    permissoes JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Atualizar Profiles com Cargo e Controle de Sessão
ALTER TABLE profiles 
ADD COLUMN IF NOT EXISTS cargo_id BIGINT REFERENCES cargos_permissoes(id),
ADD COLUMN IF NOT EXISTS last_password_change TIMESTAMPTZ DEFAULT NOW();

