-- 4. Criar política de leitura para Cargos
ALTER TABLE cargos_permissoes ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Leitura pública de cargos" ON cargos_permissoes FOR SELECT USING (true);
CREATE POLICY "Gestão de cargos pelo DEV" ON cargos_permissoes 
FOR ALL USING (
    EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND nivel = 'DEV')
);
